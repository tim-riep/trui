// Generates one module per icon from scripts/icon-data.mjs, plus an index
// with all icons and the catalog. With --check, fails if the generated
// files are not up to date.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { categories, icons } from './icon-data.mjs';
import { headerFor } from './license-header.mjs';

const dir = 'packages/trui/src/icons';
const setDir = join(dir, 'set');
const check = process.argv.includes('--check');
const header = `${headerFor('.ts')}\n// Generated by scripts/gen-icons.mjs from scripts/icon-data.mjs. Do not edit.\n`;

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const exportName = (name) => `${camel(name)}Icon`;

const files = new Map();
const names = new Set();
for (const icon of icons) {
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(icon.name))
    throw new Error(`invalid icon name ${icon.name}`);
  if (names.has(icon.name)) throw new Error(`duplicate icon ${icon.name}`);
  if (!categories[icon.category]) throw new Error(`unknown category of ${icon.name}`);
  names.add(icon.name);
  const shapes = JSON.stringify(icon.shapes);
  const options = icon.mirrorInRtl ? ', { mirrorInRtl: true }' : '';
  files.set(
    join(setDir, `${icon.name}.ts`),
    `${header}\nimport { defineIcon } from '@tim-riep/trui/core';\n\n/** The icon \`${icon.name}\` (${categories[icon.category].toLowerCase()}). */\nexport const ${exportName(icon.name)} = /* @__PURE__ */ defineIcon('${icon.name}', ${shapes}${options});\n`,
  );
}

const sorted = [...icons].sort((a, b) => a.name.localeCompare(b.name));
const index = [
  header,
  "import type { IconDefinition } from '@tim-riep/trui/core';",
  ...sorted.map((i) => `import { ${exportName(i.name)} } from './set/${i.name}';`),
  '',
  ...sorted.map((i) => `export { ${exportName(i.name)} } from './set/${i.name}';`),
  '',
  '/** All icons of the set. Importing it puts every icon into the bundle. */',
  `export const allIcons: readonly IconDefinition[] = [${sorted.map((i) => exportName(i.name)).join(', ')}];`,
  '',
  '/** Categories of the icon set with their labels. */',
  `export const iconCategories = ${JSON.stringify(categories)} as const;`,
  '',
  '/** The category of every icon of the set, by name. */',
  `export const iconCategoryByName: Readonly<Record<string, keyof typeof iconCategories>> = ${JSON.stringify(
    Object.fromEntries(sorted.map((i) => [i.name, i.category])),
  )};`,
  '',
].join('\n');
files.set(join(dir, 'index.ts'), index);

let stale = [];
for (const [file, content] of files) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== content) stale.push(file);
}
const existing = existsSync(setDir) ? readdirSync(setDir).map((f) => join(setDir, f)) : [];
const orphans = existing.filter((f) => !files.has(f));

if (check) {
  stale = [...stale, ...orphans];
  if (stale.length > 0) {
    console.error('Generated icon files are not up to date; run node scripts/gen-icons.mjs:');
    for (const f of stale) console.error(`  ${f}`);
    process.exit(1);
  }
} else {
  mkdirSync(setDir, { recursive: true });
  for (const f of orphans) rmSync(f);
  for (const f of stale) writeFileSync(f, files.get(f));
  console.log(`${icons.length} icons, ${stale.length} files written, ${orphans.length} removed`);
}
